    private void atualizarLista() {

    modeloLista.clear();

    if (mesaSelecionada == -1) {
        return;
    }

    for (String item : mesas[mesaSelecionada]) {
        modeloLista.addElement(item);
    }
}
    private void selecionarMesa(int numeroMesa) {

    mesaSelecionada = numeroMesa;

    atualizarLista();

    jTextField1.setText(
            String.format("R$ %.2f",
            totais[mesaSelecionada])
    );
}

