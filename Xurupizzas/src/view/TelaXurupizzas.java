    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    if (mesaSelecionada == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione uma mesa primeiro!"
        );

        return;
    }

    String produto = jComboBox1.getSelectedItem().toString();

    double valor = 0;

    switch (produto) {

        case "Pizza Calabresa":
            valor = 50;
            break;

        case "Pizza Frango":
            valor = 55;
            break;

        case "Pizza Portuguesa":
            valor = 60;
            break;

        case "Refrigerante":
            valor = 8;
            break;

        case "Suco":
            valor = 7;
            break;
    }

    mesas[mesaSelecionada]
            .add(produto + " - R$ " + valor);

    totais[mesaSelecionada] += valor;

    atualizarLista();
        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

